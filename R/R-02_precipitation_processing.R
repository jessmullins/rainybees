## =============================================================================
## R-02_precipitation_processing.R
##
## Purpose : (1) Process raw daily precipitation data into annual winter
##               totals with lagged values (WPy0 through WPy0-6) using the
##               Montgomery Field station as the regional proxy.
##               Generates data/cleaned/precipyrs.csv used by R-03 through R-08.
##
##           (2) Test whether precipitation variance is primarily temporal or
##               spatial using a two-way ANOVA (precipitation ~ station + year)
##               across all stations. Confirms that interannual variation
##               dominates over among-station variation, justifying use of a
##               single station as the regional precipitation proxy.
##
##           (3) Test for temporal autocorrelation in winter precipitation
##               across lags 1–5 years (ACF/PACF). No significant correlations
##               confirm that annual precipitation values can be treated as
##               independent observations in downstream models.
##
## Inputs  : data/raw/sd_station_prcp.csv  — daily PRCP for all SD-area NWS
##                                           stations (columns: STATION, NAME,
##                                           DATE, PRCP in mm)
##           data/raw/site_stations.csv    — plot-to-station assignments
##                                           (generated by R-00_station_setup.R;
##                                           needed for station map only)
##
## Outputs : data/cleaned/precipyrs.csv            — annual winter totals + lags
##           figures/monthly_heatmap.png            — monthly precip heatmap
##           figures/acf_scf.png                   — ACF/PACF plot (Fig. S4)
##           figures/stations_precip.png           — annual precip by station (Fig. S3)
##           figures/stations_map.png              — map of plots and stations (Fig. S2)
##           figures/Figure1.pdf                   — precipitation bar graph (Fig. 1B)
##           results/Table_S2_ANOVA_precip.xlsx    — temporal vs spatial ANOVA
##
## Author  : [Your name]
## Date    : [Date]
## =============================================================================

# ---- packages ----
library(dplyr)
library(lubridate)
library(ggplot2)
library(tidyr)
library(car)
library(broom)
library(writexl)
library(ggmap)
library(ggrepel)
library(RColorBrewer)

## File paths
figures_dir <- "figures"
results_dir <- "results"
cleaned_dir <- "data/cleaned"
raw_dir     <- "data/raw"

## Station name constant
MONTGOMERY <- "SAN DIEGO MONTGOMERY FIELD, CA US"

# =============================================================================
# SECTION 1 — Load and parse all station data
# =============================================================================

sd_prcp <- read.csv(file.path(raw_dir, "sd_station_prcp.csv"),
                    stringsAsFactors = FALSE) %>%
  mutate(
    DATE  = ymd(DATE),
    PRCP_mm  = as.numeric(PRCP) * 25.4,   # inches → mm,
    year  = year(DATE),
    mo    = month(DATE),
    month = month(DATE, label = TRUE, abbr = TRUE)
  )

# Montgomery Field record only — used for annual totals, heatmap, ACF
precip_manual <- sd_prcp %>%
  filter(NAME == MONTGOMERY)

# =============================================================================
# SECTION 2 — Monthly heatmap (diagnostic)
# =============================================================================

monthly_precip <- precip_manual %>%
  group_by(year, month) %>%
  summarise(total_prcp = sum(PRCP_mm, na.rm = TRUE), .groups = "drop") %>%
  filter(year >= 1999)

ggplot(monthly_precip, aes(x = month, y = factor(year), fill = total_prcp)) +
  geom_tile(color = "white") +
  scale_fill_viridis_c(option = "C", name = "Monthly\nPrecip (mm)") +
  labs(x = "Month", y = "Year",
       title    = "Monthly Precipitation (1999–2024)",
       subtitle = "Montgomery Field Air Station") +
  theme_minimal(base_size = 14) +
  theme(axis.text.y = element_text(size = 7))

ggsave(file.path(figures_dir, "monthly_heatmap.png"),
       width = 8, height = 8, dpi = 300)

# =============================================================================
# SECTION 3 — Annual winter totals + lags (Montgomery Field)
#
# Nov 2010–Mar 2011 is assigned to winter year 2011.
# PRCP is already in mm.
# =============================================================================

precip_winter <- precip_manual %>%
  mutate(
    winter_year = year + if_else(mo >= 11L, 1L, 0L)
  ) %>%
  filter(mo %in% c(11, 12, 1, 2, 3))

precipitation_yearly <- precip_winter %>%
  group_by(year = winter_year) %>%
  summarize(same = sum(PRCP_mm, na.rm = TRUE), .groups = "drop") %>%
  arrange(year) %>%
  mutate(
    previous1 = dplyr::lag(same, 1),
    previous2 = dplyr::lag(same, 2),
    previous3 = dplyr::lag(same, 3),
    previous4 = dplyr::lag(same, 4),
    previous5 = dplyr::lag(same, 5),
    previous6 = dplyr::lag(same, 6)
  )

write.csv(precipitation_yearly,
          file.path(cleaned_dir, "precipyrs.csv"),
          row.names = FALSE)

average_precipitation <- mean(precipitation_yearly$same, na.rm = TRUE)

# =============================================================================
# SECTION 4 — Temporal vs. spatial variance in precipitation (Table S2)
#
# Two-way ANOVA: winter_precip ~ station + year across all stations.
# Tests whether interannual variation (temporal) explains more variance
# than among-station variation (spatial), justifying use of a single
# regional station as the precipitation proxy.
# =============================================================================

l_noplots <- c("SWS10","CrCyn","MTLA","SWI1","MTS1A-Urb",
               "UCSDN","TRR1","TRS1","SCR")

# Build station-level annual winter totals from all stations
station_yearly <- sd_prcp %>%
  filter(!NAME == "SAN DIEGO MIRAMAR NAS, CA US") %>% # missing data
  mutate(winter_year = year + if_else(mo >= 11L, 1L, 0L)) %>%
  filter(mo %in% c(11, 12, 1, 2, 3),
         year >= 2000) %>%
  group_by(NAME, year = winter_year) %>%
  summarise(same_precip = sum(PRCP_mm, na.rm = TRUE), .groups = "drop") %>%
  filter(year >= 2000, year <= 2024)

# ANOVA
precip_aov <- aov(same_precip ~ factor(NAME) + factor(year),
                  data = station_yearly)
summary(precip_aov)
car::Anova(precip_aov, type = 3)

# Residual diagnostics
par(mfrow = c(2, 2))
plot(precip_aov)
par(mfrow = c(1, 1))

# Export results
writexl::write_xlsx(broom::tidy(precip_aov),
                    file.path(results_dir, "Table_S2_ANOVA_precip.xlsx"))

# =============================================================================
# SECTION 5 — Autocorrelation test (Fig. S4)
#
# ACF and PACF on the Montgomery Field annual winter record.
# No significant correlations = years treated as independent in models.
# =============================================================================

montgomery <- precipitation_yearly %>%
  filter(year >= 2000, year <= 2024) %>%
  arrange(year)

x <- montgomery$same
n <- sum(!is.na(x))

# Lag correlation table
precip_df <- tibble::tibble(
  year = montgomery$year,
  same = x,
  lag1 = dplyr::lag(x, 1),
  lag2 = dplyr::lag(x, 2),
  lag3 = dplyr::lag(x, 3),
  lag4 = dplyr::lag(x, 4),
  lag5 = dplyr::lag(x, 5)
)

lag_corrs <- sapply(1:5, function(l) {
  cor(precip_df$same, dplyr::pull(precip_df, paste0("lag", l)),
      use = "pairwise.complete.obs")
})
lag_corrs

# ACF + PACF
acf_vals  <- acf(x,  lag.max = 5, plot = FALSE)$acf
pacf_vals <- pacf(x, lag.max = 5, plot = FALSE)$acf

acf_pacf_tbl <- tibble::tibble(
  lag  = 1:5,
  ACF  = round(acf_vals[2:6], 3),
  PACF = round(pacf_vals[1:5], 3)
)
print(acf_pacf_tbl)

sig_bound <- 2 / sqrt(n)

acf_fig <- acf_pacf_tbl %>%
  pivot_longer(cols = c(ACF, PACF), names_to = "Type", values_to = "Correlation") %>%
  ggplot(aes(x = factor(lag), y = Correlation, fill = Type)) +
  geom_col(position = "dodge", width = 0.6) +
  geom_hline(yintercept = 0, color = "black") +
  geom_hline(yintercept = c(-sig_bound, sig_bound),
             linetype = "dashed", color = "blue") +
  scale_fill_manual(values = c("ACF" = "skyblue3", "PACF" = "tan3")) +
  labs(
    title    = "Autocorrelation of Winter Precipitation — Montgomery Field",
    subtitle = sprintf("95%% significance bounds (±%.2f), n = %d", sig_bound, n),
    x = "Lag (years)", y = "Correlation"
  ) +
  theme_minimal(base_size = 14) +
  theme(legend.position = "bottom")

ggsave(file.path(figures_dir, "acf_scf.png"),
       acf_fig, width = 6, height = 4, dpi = 300)

