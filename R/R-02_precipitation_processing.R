# =============================================================================
# SECTION 8 — Precipitation bar graph (Fig. 1B)
# =============================================================================

survey_years <- c(2011, 2012, 2015, 2016, 2022, 2023, 2024)

pdat <- precipitation_yearly %>%
  transmute(
    year      = as.integer(year),
    precip    = same,
    year_type = if_else(year %in% survey_years, "Survey year", "Non-survey year")
  ) %>%
  filter(year >= 2010, year <= 2024)

stats_25_ci <- precipitation_yearly %>%
  filter(year >= 2000, year <= 2024) %>%
  summarise(
    n       = sum(!is.na(same)),
    mean_p  = mean(same, na.rm = TRUE),
    sd_p    = sd(same,   na.rm = TRUE),
    se_p    = sd_p / sqrt(n),
    ci_low  = mean_p - qt(0.975, df = n - 1) * se_p,
    ci_high = mean_p + qt(0.975, df = n - 1) * se_p
  )

conf95 <- ggplot(pdat,
                 aes(x = factor(year), y = precip, fill = year_type)) +
  geom_col(width = 0.82) +
  geom_rect(data = stats_25_ci,
            aes(xmin = -Inf, xmax = Inf, ymin = ci_low, ymax = ci_high),
            inherit.aes = FALSE, fill = "grey70", alpha = 0.25) +
  geom_hline(aes(yintercept = mean_p), data = stats_25_ci,
             linewidth = 1.0, linetype = "dashed", color = "grey20") +
  geom_hline(aes(yintercept = ci_low),  data = stats_25_ci,
             linetype = "dotted", color = "grey20") +
  geom_hline(aes(yintercept = ci_high), data = stats_25_ci,
             linetype = "dotted", color = "grey20") +
  scale_fill_manual(
    values = c("Non-survey year" = "grey80", "Survey year" = "grey35"),
    name   = NULL
  ) +
  labs(x = NULL, y = "Winter precipitation (mm)") +
  theme_classic(base_size = 13) +
  theme(axis.text.x = element_text(angle = 45, hjust = 1))

ggsave(file.path(figures_dir, "Figure1.pdf"),
       conf95, width = 173, height = 100, units = "mm")
