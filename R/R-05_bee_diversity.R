    Metric         = metric_name,
    model          = "prev+same",
    R2_marginal    = r2_full["R2m"],
    R2_conditional = r2_full["R2c"]
  )
  print(r2_tab)
  
  fe <- broom.mixed::tidy(m_full_reml, effects = "fixed", conf.int = TRUE)
  print(fe)
  
  # Use safe centering offsets for this subset
  prev_off <- centering_offset(dd$previous1, dd$previous1_c)
  same_off <- centering_offset(dd$same,      dd$same_c)
  
  prev_seq <- seq(min(dd$previous1_c, na.rm = TRUE),
                  max(dd$previous1_c, na.rm = TRUE), length.out = 200)
  same_seq <- seq(min(dd$same_c,      na.rm = TRUE),
                  max(dd$same_c,      na.rm = TRUE), length.out = 200)
  
  pred_prev <- ggeffects::ggpredict(
    m_full_reml,
    terms     = c("previous1_c [prev_seq]"),
    condition = list(same_c = 0)
  ) %>% as.data.frame() %>% dplyr::mutate(x_mm = x + prev_off)
  
  pred_same <- ggeffects::ggpredict(
    m_full_reml,
    terms     = c("same_c [same_seq]"),
    condition = list(previous1_c = 0)
  ) %>% as.data.frame() %>% dplyr::mutate(x_mm = x + same_off)
  
  p_prev <- ggplot2::ggplot() +
    ggplot2::geom_point(data = dd, ggplot2::aes(x = previous1, y = Value),
