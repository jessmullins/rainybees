mean_same  <- mean(precipitation_yearly$same,      na.rm = TRUE)
mean_prev  <- mean(precipitation_yearly$previous1, na.rm = TRUE)
mean_prev2 <- mean(precipitation_yearly$previous2, na.rm = TRUE)

#### 2) Coverage-standardized Hill numbers (q = 0,1,2) ####

# 2.1 Build wide species-by-sample matrix from df_analysis
# df_analysis uses fieldNumber; rename to Plot for consistency with downstream code
allbees <- df_analysis %>%
  rename(Plot = fieldNumber) %>%
  mutate(
    year      = factor(year, levels = survey_years),
    Count     = as.numeric(individualCount),
    plot_year = paste(Plot, year, sep = "_")
  ) %>%
  filter(
  #  !scientificName  %in% indicators,  # remove to test indicator species effect
  )

comm <- allbees %>%
  group_by(plot_year, Plot, year, Type, scientificName) %>%
  summarise(n = sum(Count), .groups = "drop") %>%
  pivot_wider(names_from = scientificName, values_from = n, values_fill = 0)

meta <- comm %>%
  dplyr::select(plot_year, Plot, year, Type)

species_cols <- setdiff(names(comm), c("plot_year","Plot","year","Type"))

# Turn each row into a vector of positive counts for iNEXT
abund_list <- apply(
  comm[, species_cols, drop = FALSE],
  1,
  function(z) {
    z <- as.numeric(z)
    z[z > 0]
  }
)
names(abund_list) <- comm$plot_year

# 2.2 Estimate Hill numbers at shared coverage target from R-01
# target_cov loaded above — same value used for RDA and body size analyses
est <- iNEXT::estimateD(
  abund_list,
  q        = c(0, 1, 2),
  datatype = "abundance",
  base     = "coverage",
  level    = target_cov
) %>%
  as_tibble()

# 2.4 Long coverage dataset
long_cov <- est %>%
  transmute(
    plot_year = Assemblage,
    Order.q,
    SC,
    qD
  ) %>%
  left_join(meta, by = "plot_year") %>%
  mutate(
    Metric = dplyr::recode(
      Order.q,
      `0` = "Richness",
      `1` = "Hill_Shannon",
      `2` = "Hill_Simpson"
    ),
    Method = paste0("Coverage (common SC = ", round(SC[1], 2), ")")
  ) %>%
  dplyr::select(
    Plot, Type, year, plot_year, Metric,
    Value = qD,
    common_coverage = SC, Method
  )

# 2.5 Join precipitation + center
long_cov <- long_cov %>%
  left_join(
    precipitation_yearly %>%
      dplyr::select(year, same, previous1, previous2),
    by = "year"
  ) %>%
  mutate(
    same_c      = same      - mean_same,
    previous1_c = previous1 - mean_prev,
    previous2_c = previous2 - mean_prev2
  )

# Main working dataset
long_data <- long_cov

# Colors and helper 
col_vals   <- c(Reserve = "#2C7C4D", Fragment = "#BDBDBD")
shape_vals <- c(Reserve = 15,       Fragment = 16)  # 15 = filled square, 16 = filled circle


get_r2 <- function(m) {
  r2 <- suppressWarnings(MuMIn::r.squaredGLMM(m))
  c(R2m = as.numeric(r2[1, "R2m"]), R2c = as.numeric(r2[1, "R2c"]))
}

#### 3) Richness (q = 0) ####

# 3.1 Subset data
dd_rich <- long_data %>%
  filter(Metric == "Richness") %>%
  drop_na(Value, Plot, Type, same, previous1, same_c, previous1_c) %>%
  mutate(Type = forcats::fct_relevel(Type, "Reserve", "Fragment"))

# 3.2 Model formulas
form_rich_prev  <- Value ~ Type * previous1_c + (1 | Plot)
form_rich_same  <- Value ~ Type * same_c      + (1 | Plot)
form_rich_full  <- Value ~ Type * previous1_c + Type * same_c + (1 | Plot)

# 3.3 Fit models with ML for AIC
m_rich_prev_ml <- lmer(form_rich_prev, data = dd_rich, REML = FALSE)
m_rich_same_ml <- lmer(form_rich_same, data = dd_rich, REML = FALSE)
m_rich_full_ml <- lmer(form_rich_full, data = dd_rich, REML = FALSE)

aic_rich <- tibble(
  model   = c("prev_only", "same_only", "prev+same"),
  formula = c(
    deparse(form_rich_prev),
    deparse(form_rich_same),
    deparse(form_rich_full)
  ),
  AIC     = c(
    AIC(m_rich_prev_ml),
    AIC(m_rich_same_ml),
    AIC(m_rich_full_ml)
  )
) %>%
  arrange(AIC)

print(aic_rich)

# 3.4 Refit models with REML for inference
m_rich_prev_reml <- lmer(form_rich_prev, data = dd_rich, REML = TRUE)
m_rich_same_reml <- lmer(form_rich_same, data = dd_rich, REML = TRUE)
m_rich_full_reml <- lmer(form_rich_full, data = dd_rich, REML = TRUE)

# Type III ANOVA for full model
anova_rich_full <- car::Anova(m_rich_full_reml, type = "III")
print(anova_rich_full)

# R2 (Nakagawa) for full model
r2_rich_full <- performance::r2_nakagawa(m_rich_full_reml)
print(r2_rich_full)
summary(m_rich_full_reml )
# Fixed effects (CIs) and glance
coef_rich_full <- broom.mixed::tidy(
  m_rich_full_reml,
  effects = "fixed",
  conf.int = TRUE
)
print(coef_rich_full)

glance_rich_full <- broom.mixed::glance(m_rich_full_reml)
print(glance_rich_full)

# 3.5 R2 comparison across models
r2_mat_rich <- rbind(
  get_r2(m_rich_prev_reml),
  get_r2(m_rich_same_reml),
  get_r2(m_rich_full_reml)
)

r2_table_rich <- tibble(
  model          = c("prev_only", "same_only", "prev+same"),
  formula        = c(
    deparse(form_rich_prev),
    deparse(form_rich_same),
    deparse(form_rich_full)
  ),
  R2_marginal    = r2_mat_rich[, "R2m"],
  R2_conditional = r2_mat_rich[, "R2c"]
)

rich_m <- r2_table_rich$R2_marginal[r2_table_rich$model == "prev+same"]
rich_c <- r2_table_rich$R2_conditional[r2_table_rich$model == "prev+same"]

r2_table_rich <- r2_table_rich %>%
  mutate(
    dR2m_vs_full = R2_marginal    - rich_m,
    dR2c_vs_full = R2_conditional - rich_c
  )

print(r2_table_rich)

