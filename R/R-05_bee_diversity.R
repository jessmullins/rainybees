# SECTION 6 — Model diagnostics
#
# Addresses reviewer concerns about Gaussian assumptions for bounded responses.
# For each full model (richness, Hill-Shannon, Hill-Simpson):
#   (1) Box-Cox test — identifies optimal power transformation
#   (2) Log-transform check — plots raw vs log(Value) distributions
#   (3) DHARMa simulated residuals — tests for misspecification, dispersion,
#       outliers, and residual autocorrelation
#   (4) performance::check_model — visual diagnostics panel
#
# All diagnostic plots saved to figures/diagnostics/
# DHARMa test results saved to results/diagnostics_dharma.xlsx
#
# See supplement for full diagnostic outputs. Models are Gaussian lmer fits;
# diagnostics confirm acceptability of this approximation given that diversity
# values are not concentrated near zero.
# =============================================================================

library(DHARMa)
dir.create(file.path(figures_dir, "diagnostics"), showWarnings = FALSE)

run_diagnostics <- function(model, metric_name, diag_dat) {

  diag_dat <- as.data.frame(diag_dat)  # force plain data.frame

  cat("\n==============================\n")
  cat("Diagnostics:", metric_name, "\n")
  cat("==============================\n")

  # ---- 1) Box-Cox transformation test ----
  y <- diag_dat[["Value"]]
  lambdas <- seq(-2, 2, by = 0.1)
  log_liks <- sapply(lambdas, function(lam) {
    y_trans <- if (abs(lam) < 1e-10) log(y) else (y^lam - 1) / lam
    sum(dnorm(y_trans, mean(y_trans), sd(y_trans), log = TRUE)) +
      (lam - 1) * sum(log(y))
  })
  lambda_opt <- lambdas[which.max(log_liks)]
  cat("Box-Cox optimal lambda:", round(lambda_opt, 3),
      " (log = 0, no transform = 1)\n")

  # ---- 2) Distribution check: raw vs log ----
  png(file.path(figures_dir, "diagnostics",
                paste0(metric_name, "_distribution_check.png")),
      width = 800, height = 400, res = 120)
  par(mfrow = c(1, 2))
  hist(diag_dat[["Value"]], main = paste(metric_name, "- raw"),
       xlab = "Value", col = "steelblue", border = "white")
  hist(log(diag_dat[["Value"]] + 0.001), main = paste(metric_name, "- log"),
       xlab = "log(Value)", col = "coral", border = "white")
  par(mfrow = c(1, 1))
  dev.off()

  # ---- 3) DHARMa simulated residuals ----
  sim_res <- DHARMa::simulateResiduals(model, n = 1000, plot = FALSE)

  png(file.path(figures_dir, "diagnostics",
                paste0(metric_name, "_dharma_residuals.png")),
      width = 900, height = 500, res = 120)
  plot(sim_res, main = metric_name)
  dev.off()

  disp_test    <- DHARMa::testDispersion(sim_res,  plot = FALSE)
  outlier_test <- DHARMa::testOutliers(sim_res,    plot = FALSE)
  unif_test    <- DHARMa::testUniformity(sim_res,  plot = FALSE)

  cat("DHARMa dispersion test p =", round(disp_test$p.value,    4), "\n")
  cat("DHARMa outlier test p =",    round(outlier_test$p.value, 4), "\n")
  cat("DHARMa uniformity test p =", round(unif_test$p.value,    4), "\n")

  # ---- 4) performance::check_model ----
  perf_plot <- performance::check_model(model)
  ggplot2::ggsave(
    file.path(figures_dir, "diagnostics",
              paste0(metric_name, "_check_model.png")),
    plot  = plot(perf_plot),
    width = 12, height = 10, dpi = 150
  )

  tibble::tibble(
    metric           = metric_name,
    boxcox_lambda    = round(lambda_opt,           3),
    dharma_disp_p    = round(disp_test$p.value,    4),
    dharma_outlier_p = round(outlier_test$p.value, 4),
    dharma_uniform_p = round(unif_test$p.value,    4)
  )
}

