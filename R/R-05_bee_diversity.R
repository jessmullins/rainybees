  message("Fragments-only: ", metric_name)
  message("N rows = ", nrow(dd), " | N plots = ", dplyr::n_distinct(dd$Plot))
  message("==============================")
  
  form_prev <- Value ~ previous1_c + (1 | Plot) + (1 | year)
  form_same <- Value ~ same_c      + (1 | Plot) + (1 | year)
  form_full <- Value ~ previous1_c + same_c + (1 | Plot) + (1 | year)
  form_null <- Value ~ (1 | Plot) + (1 | year)   # null model: random effects only, no fixed effects
  
  m_prev_ml <- lmer(form_prev, data = dd, REML = FALSE)
  m_same_ml <- lmer(form_same, data = dd, REML = FALSE)
  m_full_ml <- lmer(form_full, data = dd, REML = FALSE)
  m_null_ml <- lmer(form_null, data = dd, REML = FALSE)
  
