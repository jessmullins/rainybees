# --- Fit the SAME model structure used throughout (Type * precip x2, +year) -
fit_noind_model <- function(metric_name) {
  dd <- long_cov_noind %>%
    filter(Metric == metric_name) %>%
    drop_na(Value, Plot, Type, same, previous1, same_c, previous1_c) %>%
    mutate(Type = forcats::fct_relevel(Type, "Reserve", "Fragment"))
  
  m <- lmer(Value ~ Type * previous1_c + Type * same_c + (1 | Plot) + (1 | year),
            data = dd, REML = TRUE)
  cat("\n---", metric_name, "(indicators removed) singular fit?",
      lme4::isSingular(m), "---\n")
  a <- car::Anova(m, type = "III")
  print(a)
  list(model = m, anova = a, data = dd)
}

