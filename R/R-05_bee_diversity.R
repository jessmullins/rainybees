one_panel <- function(metric_name, type_name, which = c("prev", "same"),
                      show_row_title = FALSE, dat = long_data) {
  which <- match.arg(which)
  
  dd <- dat %>%
    filter(Metric == metric_name, Type == type_name) %>%
    drop_na(Value, Plot, previous1, same, previous1_c, same_c)
  
  m <- lmer(Value ~ previous1_c + same_c + (1 | Plot), data = dd, REML = TRUE)
  
  if (which == "prev") {
    pred <- ggpredict(m, terms = "previous1_c [all]", condition = list(same_c = 0)) %>%
      as.data.frame() %>%
      mutate(x_mm = x + mean(dd$previous1, na.rm = TRUE))
    pts <- dd %>% transmute(x = previous1, Value = Value)
  } else {
    pred <- ggpredict(m, terms = "same_c [all]", condition = list(previous1_c = 0)) %>%
      as.data.frame() %>%
      mutate(x_mm = x + mean(dd$same, na.rm = TRUE))
    pts <- dd %>% transmute(x = same, Value = Value)
  }
  
  ggplot() +
    geom_point(data = pts, aes(x = x, y = Value),
               color = "gray40", alpha = 0.35, size = 1.8) +
    geom_ribbon(data = pred, aes(x = x_mm, ymin = conf.low, ymax = conf.high),
                fill = type_cols[[type_name]], alpha = 0.20) +
    geom_line(data = pred, aes(x = x_mm, y = predicted),
              color = type_cols[[type_name]], linewidth = 1.1) +
    theme_classic(base_size = 13) +
    theme(
      axis.title.x = element_blank(),
      axis.title.y = element_blank(),
      plot.title = element_text(face = "bold", hjust = 0)
    ) +
    labs(title = if (show_row_title) metric_titles[[metric_name]] else NULL)
}

make_6panel_one_type <- function(type_name, dat = long_data) {
  
  # For each row: left (prev) shows the metric title; right (same) has no title.
  panels <- list(
    one_panel("Richness",     type_name, "prev", show_row_title = TRUE,  dat = dat),
    one_panel("Richness",     type_name, "same", show_row_title = FALSE, dat = dat),
    
    one_panel("Hill_Shannon", type_name, "prev", show_row_title = TRUE,  dat = dat),
    one_panel("Hill_Shannon", type_name, "same", show_row_title = FALSE, dat = dat),
    
    one_panel("Hill_Simpson", type_name, "prev", show_row_title = TRUE,  dat = dat),
    one_panel("Hill_Simpson", type_name, "same", show_row_title = FALSE, dat = dat)
  )
  
  p_main <- wrap_plots(panels, ncol = 2)
  
  # single bottom label row
