# Helper: run fragment-only model set for one metric
run_frag_models <- function(metric_name, dat = long_data) {
  
  dd <- dat %>%
    dplyr::filter(Metric == metric_name, Type == "Fragment") %>%
    tidyr::drop_na(Value, Plot, year, same, previous1, same_c, previous1_c)
  
  message("\n==============================")
  message("Fragments-only: ", metric_name)
  message("N rows = ", nrow(dd), " | N plots = ", dplyr::n_distinct(dd$Plot))
  message("==============================")
  
  # Model formulas (no Type term, since fragments only)
  form_prev <- Value ~ previous1_c + (1 | Plot)
  form_same <- Value ~ same_c      + (1 | Plot)
  form_full <- Value ~ previous1_c + same_c + (1 | Plot)
  
  # Fit with ML for AIC comparisons
  m_prev_ml <- lmer(form_prev, data = dd, REML = FALSE)
  m_same_ml <- lmer(form_same, data = dd, REML = FALSE)
  m_full_ml <- lmer(form_full, data = dd, REML = FALSE)
  
  aic_tab <- tibble::tibble(
    Metric  = metric_name,
    model   = c("prev_only", "same_only", "prev+same"),
    formula = c(deparse(form_prev), deparse(form_same), deparse(form_full)),
    AIC     = c(AIC(m_prev_ml), AIC(m_same_ml), AIC(m_full_ml))
  ) %>% dplyr::arrange(AIC)
  
  print(aic_tab)
  
  # Refit with REML for inference (use the full model as the main inference target)
  m_full_reml <- lmer(form_full, data = dd, REML = TRUE)
  
  # Type III tests (consistent with your main pipeline)
  anova_full <- car::Anova(m_full_reml, type = "III")
  print(anova_full)
  
  # R2 (Nakagawa-style via MuMIn, matching your helper)
  r2_full <- get_r2_safe(m_full_reml)
  r2_tab <- tibble::tibble(
    Metric = metric_name,
    model  = "prev+same",
    R2_marginal    = r2_full["R2m"],
    R2_conditional = r2_full["R2c"]
  )
  print(r2_tab)
  
  # Fixed effects table w/ CI
  fe <- broom.mixed::tidy(m_full_reml, effects = "fixed", conf.int = TRUE)
  print(fe)
  
  # Optional: quick plots (prev and same) for fragments-only
  pred_prev <- ggeffects::ggpredict(
    m_full_reml,
    terms     = c("previous1_c [all]"),
    condition = list(same_c = 0)
  ) %>%
    as.data.frame() %>%
    dplyr::mutate(x_mm = x + mean(dd$previous1, na.rm = TRUE))
  
  pred_same <- ggeffects::ggpredict(
    m_full_reml,
    terms     = c("same_c [all]"),
    condition = list(previous1_c = 0)
  ) %>%
    as.data.frame() %>%
    dplyr::mutate(x_mm = x + mean(dd$same, na.rm = TRUE))
  
  p_prev <- ggplot2::ggplot() +
    ggplot2::geom_point(
      data = dd,
      ggplot2::aes(x = previous1, y = Value),
      alpha = 0.35, size = 2
    ) +
    ggplot2::geom_ribbon(
      data = pred_prev,
      ggplot2::aes(x = x_mm, ymin = conf.low, ymax = conf.high),
      alpha = 0.25
    ) +
    ggplot2::geom_line(
      data = pred_prev,
      ggplot2::aes(x = x_mm, y = predicted),
      linewidth = 1.2
    ) +
    ggplot2::theme_classic() +
    ggplot2::labs(x = "Previous-year winter precipitation (mm)",
                  y = paste0(metric_name, " (fragments only)"))
  
  p_same <- ggplot2::ggplot() +
    ggplot2::geom_point(
      data = dd,
      ggplot2::aes(x = same, y = Value),
      alpha = 0.35, size = 2
    ) +
    ggplot2::geom_ribbon(
      data = pred_same,
      ggplot2::aes(x = x_mm, ymin = conf.low, ymax = conf.high),
      alpha = 0.25
    ) +
    ggplot2::geom_line(
      data = pred_same,
      ggplot2::aes(x = x_mm, y = predicted),
      linewidth = 1.2
    ) +
    ggplot2::theme_classic() +
    ggplot2::labs(x = "Same-year winter precipitation (mm)",
                  y = NULL)
  
  p_both <- p_prev + p_same + patchwork::plot_layout(ncol = 2)
  print(p_both)
  
  # Save plots (filenames safe)
  safe_metric <- gsub("[^A-Za-z0-9_]+", "_", metric_name)
  ggplot2::ggsave(
    filename = paste0("fragOnly_", safe_metric, "_precip.png"),
    plot = p_both, width = 10, height = 4, units = "in", dpi = 300
  )
  
  list(
    data      = dd,
    aic       = aic_tab,
    anova     = broom::tidy(anova_full),
    fixed     = fe,
    r2        = r2_tab,
    model_reml = m_full_reml
  )
}

