    ggplot2::geom_line(data = pred_prev,
                       ggplot2::aes(x = x_mm, y = predicted), linewidth = 1.2) +
    ggplot2::theme_classic() +
    ggplot2::labs(x = "Previous-year winter precipitation (mm)",
                  y = paste0(metric_name, " (fragments only)"))
  
  p_same <- ggplot2::ggplot() +
    ggplot2::geom_point(data = dd, ggplot2::aes(x = same, y = Value),
                        color = "gray40", alpha = 0.35, size = 1.8) +
    ggplot2::geom_ribbon(data = pred_same,
                         ggplot2::aes(x = x_mm, ymin = conf.low, ymax = conf.high),
