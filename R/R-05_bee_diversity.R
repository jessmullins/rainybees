get_r2 <- function(m) {
  r2 <- suppressWarnings(MuMIn::r.squaredGLMM(m))
  c(R2m = as.numeric(r2[1, "R2m"]), R2c = as.numeric(r2[1, "R2c"]))
}

# Helper: compute the true back-transform constant for a centered variable.
# Works correctly regardless of whether centering happened on the full dataset
# or a subset (e.g. after filtering/dropping NAs).
centering_offset <- function(raw, centered) {
  mean(raw, na.rm = TRUE) - mean(centered, na.rm = TRUE)
}

