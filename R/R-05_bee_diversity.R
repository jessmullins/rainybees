    a1 %>% dplyr::select(term, Chisq_full_data = Chisq, P_full_data = `Pr(>Chisq)`),
    a2 %>% dplyr::select(term, Chisq_no_indicators = Chisq, P_no_indicators = `Pr(>Chisq)`),
    by = "term"
  ) %>% mutate(Metric = metric_name, .before = 1)
}

