# SECTION 6 — Model diagnostics (Table S5)
#
# Runs Box-Cox + DHARMa diagnostics on the three +year diversity models.
# Richness flags a DHARMa outlier issue driven by a single site (SWI4);
# Section 6b investigates this and confirms results are robust to its
# exclusion (see Appendix S1 note).
