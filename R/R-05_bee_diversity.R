# --- Reviewer-requested addition: year as a random effect --------------------
# Sites sampled in the same year share the same WPy0/WPy0-1 value (these are
# year-level, not site-level, predictors), so treating site-years as fully
# independent overstates the effective sample size for the precipitation
# effect. Adding (1 | year) forces the precipitation effect to be estimated
# from genuine between-year variation (~7 years), which is the statistically
# honest approach -- expect wider CIs / possibly weaker significance for
# WPy0 and WPy0-1 specifically, since that is the correction working as
# intended, not a bug.
form_rich_full_year <- Value ~ Type * previous1_c + Type * same_c + (1 | Plot) + (1 | year)
m_rich_full_year_reml <- lmer(form_rich_full_year, data = dd_rich, REML = TRUE)
cat("\nSingular fit (year RE model)?", lme4::isSingular(m_rich_full_year_reml), "\n")

anova_rich_full_year <- car::Anova(m_rich_full_year_reml, type = "III")
print(anova_rich_full_year)

compare_anova <- function(anova_no_year, anova_with_year, metric_name) {
  a1 <- as.data.frame(anova_no_year)   %>% tibble::rownames_to_column("term")
  a2 <- as.data.frame(anova_with_year) %>% tibble::rownames_to_column("term")
  full_join(
    a1 %>% dplyr::select(term, Chisq_no_year = Chisq, P_no_year = `Pr(>Chisq)`),
    a2 %>% dplyr::select(term, Chisq_with_year = Chisq, P_with_year = `Pr(>Chisq)`),
    by = "term"
  ) %>%
    mutate(Metric = metric_name, .before = 1)
}

