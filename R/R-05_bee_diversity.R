dir.create(file.path(figures_dir, "diagnostics"), showWarnings = FALSE)

run_diagnostics <- function(model, metric_name, diag_dat) {
  
  diag_dat <- as.data.frame(diag_dat)
  y <- diag_dat[["Value"]]
  
  cat("\n==============================\n")
  cat("Diagnostics:", metric_name, "\n")
  cat("==============================\n")
  
  # Box-Cox optimal lambda
  lambdas <- seq(-2, 2, by = 0.1)
  log_liks <- sapply(lambdas, function(lam) {
    y_trans <- if (abs(lam) < 1e-10) log(y) else (y^lam - 1) / lam
    sum(dnorm(y_trans, mean(y_trans), sd(y_trans), log = TRUE)) + (lam - 1) * sum(log(y))
  })
  lambda_opt <- lambdas[which.max(log_liks)]
  cat("Box-Cox optimal lambda:", round(lambda_opt, 3), " (log = 0, no transform = 1)\n")
  
  # Raw vs. log distribution check
  png(file.path(figures_dir, "diagnostics", paste0(metric_name, "_distribution_check.png")),
      width = 800, height = 400, res = 120)
  par(mfrow = c(1, 2))
  hist(y, main = paste(metric_name, "- raw"), xlab = "Value", col = "steelblue", border = "white")
  hist(log(y + 0.001), main = paste(metric_name, "- log"), xlab = "log(Value)", col = "coral", border = "white")
  par(mfrow = c(1, 1))
  dev.off()
  
  # DHARMa
  sim_res      <- DHARMa::simulateResiduals(model, n = 1000, plot = FALSE)
  disp_test    <- DHARMa::testDispersion(sim_res,  plot = FALSE)
  outlier_test <- DHARMa::testOutliers(sim_res,    plot = FALSE)
  unif_test    <- DHARMa::testUniformity(sim_res,  plot = FALSE)
  
  png(file.path(figures_dir, "diagnostics", paste0(metric_name, "_dharma_residuals.png")),
      width = 900, height = 500, res = 120)
  plot(sim_res, main = metric_name)
  dev.off()
  
  cat("DHARMa dispersion p =", round(disp_test$p.value,    4), "\n")
  cat("DHARMa outlier p =",    round(outlier_test$p.value, 4), "\n")
  cat("DHARMa uniformity p =", round(unif_test$p.value,    4), "\n")
  
  perf_plot <- performance::check_model(model)
  ggplot2::ggsave(
    file.path(figures_dir, "diagnostics", paste0(metric_name, "_check_model.png")),
    plot = plot(perf_plot), width = 12, height = 10, dpi = 150
  )
  
  list(
    summary = tibble::tibble(
      metric           = metric_name,
      boxcox_lambda    = round(lambda_opt,           3),
      dharma_disp_p    = round(disp_test$p.value,    4),
      dharma_outlier_p = round(outlier_test$p.value, 4),
      dharma_uniform_p = round(unif_test$p.value,    4)
    ),
    sim_res = sim_res   # kept for downstream outlier-row lookup, e.g. Richness below
  )
}

